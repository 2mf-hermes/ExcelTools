const dicts: Record<Locale, Dict> = {
  "zh-TW": zhTW,
  "zh-CN": zhCN,
  en,
  ja,
  ko,
};

/** Canonical key list used for localization QA. */
export const I18N_KEYS: string[] = Object.keys(en).sort();

export function detectLocale(systemLang: string | undefined): Locale {
  const l = (systemLang || "").toLowerCase().replace("_", "-");
  if (l.startsWith("zh-cn") || l.startsWith("zh-hans") || l === "zh") return "zh-CN";
  if (l.startsWith("zh-tw") || l.startsWith("zh-hant") || l.startsWith("zh-hk") || l.startsWith("zh-mo"))
    return "zh-TW";
  if (l.startsWith("ja")) return "ja";
  if (l.startsWith("ko")) return "ko";
  if (l.startsWith("en")) return "en";
  return "zh-TW";
}

export function t(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  let s = dicts[locale][key] ?? dicts.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replace(`{${k}}`, String(v));
    }
  }
  return s;
}

/** Returns keys missing from any locale (for QA). */
export function missingI18nKeys(): { locale: Locale; keys: string[] }[] {
  const base = new Set(I18N_KEYS);
  return LOCALES.map((locale) => {
    const d = dicts[locale];
    const keys = [...base].filter((k) => !(k in d));
    return { locale, keys };
  }).filter((x) => x.keys.length > 0);
}
